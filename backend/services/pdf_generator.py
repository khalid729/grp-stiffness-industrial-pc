    def _single_position_page(self, s: _Sheet, group: TestGroup, test: Test, unit: str):
        y = _header(s, 0, self.logo, f'ASTM D2412-02 — {_angle(test.angle or 0)}', group.passed)
        y = self._group_info(s, y, group)
        stat = lambda label, text: [(label, SANS, 12, GRAY_500, 16), (text, MONO_BOLD, 12, BLACK, 16)]

        if test.v_id:
            y = _heading(s, y, 'Sample Measurements')
            y = _stat_cards(s, y, [
                stat('Horizontal ID', f'{_fixed(test.h_id, 2)} mm'),
                stat('Vertical ID', f'{_fixed(test.v_id, 2)} mm'),
                stat('Wall Thickness', f'{_fixed(test.wall_thickness, 2)} mm'),
                stat('Ring Length', f'{_num(test.ring_length or None)} mm'),
                stat('Init Defl (mm)', f'{_fixed(test.h_id - test.v_id, 2) if test.h_id and test.v_id else "-"} mm'),
                stat('Initial Deflection', f'{_fixed(test.initial_deflection, 3)}%'),
            ], pad=8) + 12

        y = _heading(s, y, 'Results')
        label = lambda text: (text, SANS, 12, GRAY_500, 16)
        value = lambda text: (text, MONO_BOLD, 20, BLACK, 28)
        stis = _fixed(test.stis, 0) if test.stis is not None else _force(test.ring_stiffness, unit)
        y = _stat_cards(s, y, [
            [label('Pipe Stiffness (STIS)'), value(stis), ('N/m²', SANS, 10, GRAY_400, 15)],
            [label('Force at Target'), value(_force(test.force_at_target, unit)), (unit, SANS, 10, GRAY_400, 15)],
            [label('Target SN'), value(f'SN {group.target_sn_class or "-"}')],
        ], pad=12, radius=8)
        if test.ei_over_r3 or test.e_modulus:
            y = _stat_cards(s, y + 8, [
                stat('EI/R³', f'{_fixed(test.ei_over_r3, 4)} N/mm²'),
                stat('E-Modulus', f'{_fixed(test.e_modulus, 0)} N/mm²'),
                stat('C-Factor', _fixed(test.c_factor, 4)),
            ], pad=8)
        y += 12

        y = _heading(s, y, 'Force-Deflection Curve')
        y = _chart(s, y, test) + 12
        _footer(s, y + 4)
